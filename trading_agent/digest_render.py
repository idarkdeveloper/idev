def document(data: dict[str, Any], summary: str | None = None, writer: str = "none",
             images: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    kind = data["kind"]
    try:
        day = datetime.fromisoformat(data["generated_at"]).strftime("%a %d %b %Y")
    except ValueError:
        day = data.get("date", "")
    head = (f"Today: what to buy and what to watch, {day}" if kind == "morning" else f"Close: your portfolio, {day}")
    blocks = []
    if summary and writer == "rules":
        blocks.append(_block("In short (written by the rules)", [summary]))
    elif summary:   # a model wrote it: say which, and to check the numbers
        who = "Claude Haiku" if "claude-haiku" in writer else writer
        blocks.append(_block(f"In short (written by {who} — check the numbers below)", [summary]))
    saved = None
    if kind == "evening" and isinstance(data.get("groww"), dict):
        saved = data["groww"].get("saved")
    elif kind == "morning" and isinstance(data.get("watch"), dict):
        saved = next((n[len("Using "):] for n in data["watch"].get("notes", []) if n.startswith("Using ")), None)
    if saved:
        blocks.append(_block(None, ["Using " + saved + "."], tone="warn"))
    blocks += _morning_blocks(data) if kind == "morning" else _evening_blocks(data, images)
    foot = [FOOTER] + ([DELAYED] if data.get("delayed") else [])
    return {"title": head, "blocks": blocks, "footer": foot}


# -- plain text ---------------------------------------------------------------------------
def _text_table(t: dict[str, Any]) -> list[str]:
    head, rows, num = t["head"], t["rows"], set(t.get("num") or [])
    # Why / Headline columns come last and are not padded
    widths = [max(len(str(r[i])) for r in [head] + rows) for i in range(len(head))]
    out = []
    for r in [head] + rows:
        cells = []
        for i, c in enumerate(r):
            c = str(c)
            if i == len(r) - 1 and i not in num:
                cells.append(c)
            else:
                cells.append(c.rjust(widths[i]) if i in num else c.ljust(widths[i]))
        out.append("  " + "  ".join(cells))
    return out


def to_text(doc: dict[str, Any]) -> str:
    out = [doc["title"], "=" * len(doc["title"]), ""]
    for b in doc["blocks"]:
        head, sep, tail = (b["title"] or "").partition(" (")   # "IN SHORT (written by ...)": only the name is upper-cased
        if b["title"] is None and b.get("cont") and out and out[-1] == "":
            out.pop()   # a continuation of the block above: no blank line, no heading
        if b["title"] is not None or not b.get("cont"):
            out.append(head.upper() + sep + tail)
        out += [f"{k}: {v}" for k, v in b.get("kv") or []]
        out += b["lines"]
        out += [f"[Chart: {i['alt']}]" for i in b.get("images") or []]
        if b["table"]:
            out += _text_table(b["table"])
        out.append("")
    out += doc["footer"]
    return "\n".join(out) + "\n"


# -- HTML -------------------------------------------------------------------------------------
def _e(x: object) -> str:
    return _html.escape(str(x), quote=True)


def to_html(doc: dict[str, Any]) -> str:
    font = "font-family:Arial,Helvetica,sans-serif;"
    parts = [f'<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="background:#f3f4f6;{font}">'
             '<tr><td align="center" style="padding:16px">'
             '<table role="presentation" cellpadding="0" cellspacing="0" '
             'style="max-width:640px;width:100%;background:#ffffff;border:1px solid #e5e7eb">'
             f'<tr><td style="padding:16px 20px;background:#111827;color:#ffffff;font-size:18px;font-weight:bold;{font}">{_e(doc["title"])}</td></tr>']
    for b in doc["blocks"]:
        colour = TONES.get(b["tone"], TONES[None])
        side = "border-left:3px solid #d1d5db;" if b["tone"] == "muted" else ""   # a held-back candidate list: grey, never green
        parts.append(f'<tr><td style="padding:{4 if b.get("cont") else 14}px 20px 4px 20px;{side}{font}">')
        if b["title"]:
            parts.append(f'<div style="font-size:15px;font-weight:bold;color:{colour};border-bottom:1px solid #e5e7eb;padding-bottom:4px">{_e(b["title"])}</div>')
        for line in b["lines"]:
            parts.append(f'<div style="font-size:14px;color:#111827;line-height:1.45;padding-top:6px">{_e(line)}</div>')
        for img in b.get("images") or []:   # inline picture attached to the email (content id), or a data: URL in the preview
            parts.append(f'<img src="cid:{_e(img["cid"])}" alt="{_e(img["alt"])}" width="600" '
                         'style="display:block;width:100%;max-width:600px;height:auto;border:0;margin-top:8px">')
        if b.get("kv"):
            parts.append('<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin-top:6px;border-collapse:collapse;width:100%">')
            for k, v in b["kv"]:
                parts.append(f'<tr><td style="font-size:12px;color:#6b7280;padding:2px 8px 2px 0;vertical-align:top;white-space:nowrap">{_e(k)}</td>'
                             f'<td style="font-size:13px;color:#111827;padding:2px 0">{_e(v)}</td></tr>')
            parts.append("</table>")
        t = None if b.get("cards") else b["table"]   # the watch list is cards on a phone, not a table
        for card in b.get("cards") or []:
            if card.get("style") == "market":   # the index line, then the headline that names it (if any) in small type
                why = (f'<div style="font-size:11px;color:#6b7280;line-height:1.35">{_e(card["why"])}</div>' if card.get("why") else "")
                parts.append(f'<div style="margin-top:7px"><div style="font-size:13px;color:#111827">{_e(card["meta"])}</div>{why}</div>')
                continue
            if card.get("style") == "news":   # small muted line, then the headline at full width (linked when it has a link)
                head = _e(card["title"])
                if str(card.get("link") or "").startswith(("http://", "https://")):
                    head = f'<a href="{_e(card["link"])}" style="color:#1d4ed8;text-decoration:none">{head}</a>'
                parts.append(f'<div style="margin-top:9px"><div style="font-size:11px;color:#6b7280">{_e(card["meta"])}</div>'
                             f'<div style="font-size:13px;color:#111827;line-height:1.4">{head}</div></div>')
                continue
            parts.append(f'<div style="margin-top:10px"><span style="font-size:14px;font-weight:bold;color:#111827">{_e(card["title"])}</span> '
                         f'<span style="font-size:11px;color:#6b7280">{_e(card["meta"])}</span>'
                         '<ul style="margin:3px 0 0 18px;padding:0">'
                         + "".join(f'<li style="font-size:13px;color:#111827;line-height:1.4">{_e(x)}</li>' for x in card["bullets"])
                         + "</ul></div>")
        if t:
            t = t.get("html") or t     # the phone layout may differ from the text one
            num, nowrap, sub = set(t.get("num") or []), set(t.get("nowrap") or []), t.get("sub")
            tones, pad, fs = t.get("tones"), ("4px 3px" if t.get("compact") else "4px 6px"), ("12px" if t.get("compact") else "13px")
            parts.append('<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin-top:8px;border-collapse:collapse;width:100%">')
            parts.append("<tr>" + "".join(
                f'<th align="{"right" if i in num else "left"}" style="font-size:12px;color:#6b7280;padding:{pad};border-bottom:1px solid #e5e7eb">{_e(h)}</th>'
                for i, h in enumerate(t["head"])) + "</tr>")
            for n, r in enumerate(t["rows"]):
                cells = []
                for i, c in enumerate(r):
                    tone = tones[n][i] if tones else None
                    style = f"font-size:{fs};color:{TONES[tone]};padding:{pad};border-bottom:1px solid #f3f4f6;vertical-align:top;"
                    if i in num or i in nowrap:
                        style += "white-space:nowrap;"
                    extra = ""
                    if i == 0 and sub and sub[n]:
                        tip = f' title="{_e(t["sub_title"][n])}"' if t.get("sub_title") and t["sub_title"][n] else ""
                        extra = f'<div{tip} style="font-size:11px;color:#6b7280;white-space:normal">{_e(sub[n])}</div>'
                    cls = f' class="pl-{"profit" if tone == "good" else "loss"}"' if tone else ""
                    cells.append(f'<td{cls} align="{"right" if i in num else "left"}" style="{style}">{_e(c)}{extra}</td>')
                parts.append("<tr>" + "".join(cells) + "</tr>")
            parts.append("</table>")
        parts.append("</td></tr>")
    foot = "<br>".join(_e(x) for x in doc["footer"])
    parts.append(f'<tr><td style="padding:16px 20px;font-size:12px;color:#6b7280;{font}">{foot}</td></tr></table></td></tr></table>')
    return "".join(parts)


def strip_chart_mentions(text: str) -> str:
    """The text part without its "[Chart: ...]" lines (when the pictures are not sent)."""
    return re.sub(r"(?m)^\[Chart: .*\]\n", "", text)


def strip_cid_images(html: str) -> str:
    """The HTML without its inline pictures (when they cannot be sent)."""
    return re.sub(r"<img\b[^>]*\bsrc=\"cid:[^\"]*\"[^>]*>", "", html)


def inline_data_urls(html: str, images: list[dict[str, Any]] | None) -> str:
    """The HTML with each ``cid:`` picture replaced by a data: URL, for a browser or the dashboard preview."""
    for i in images or []:
        url = "data:image/png;base64," + base64.b64encode(i["content"]).decode("ascii")
        html = html.replace(f'src="cid:{i["cid"]}"', f'src="{url}"')
    return html


def render(data: dict[str, Any], summary: str | None = None, writer: str = "none",
           images: list[dict[str, Any]] | None = None) -> dict[str, str]:
    doc = document(data, summary, writer, images)
    return {"subject": subject(data), "text": to_text(doc), "html": to_html(doc)}
